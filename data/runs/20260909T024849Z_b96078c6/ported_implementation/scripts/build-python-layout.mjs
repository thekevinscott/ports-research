/**
 * Emit a `gbnf/` directory that mirrors the Python package's module layout, where every
 * file simply re-exports the corresponding TypeScript module. Code written against the
 * reference implementation's module paths (`gbnf/grammar_graph/graph_node`) then resolves
 * to the port.
 *
 * Run `node scripts/build-python-layout.mjs` after adding or renaming a module.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

/** python module path (without extension) -> TypeScript module under src/ */
const MODULES = {
  "__init__": "index",
  "GBNF": "gbnf",
  "utils/is_point_in_range": "utils/is-point-in-range",
  "utils/validate_non_empty": "utils/validate-non-empty",
  "utils/errors/__init__": "utils/errors/index",
  "utils/errors/build_error_position": "utils/errors/build-error-position",
  "utils/errors/errors_types": "utils/errors/errors-types",
  "utils/errors/get_input_as_string": "utils/errors/get-input-as-string",
  "utils/errors/grammar_parse_error": "utils/errors/grammar-parse-error",
  "utils/errors/input_parse_error": "utils/errors/input-parse-error",
  "rules_builder/__init__": "rules-builder/index",
  "rules_builder/is_word_char": "rules-builder/is-word-char",
  "rules_builder/parse_char": "rules-builder/parse-char",
  "rules_builder/parse_name": "rules-builder/parse-name",
  "rules_builder/parse_space": "rules-builder/parse-space",
  "rules_builder/rules_builder": "rules-builder/rules-builder",
  "rules_builder/rules_builder_types": "rules-builder/rules-builder-types",
  "rules_builder/symbol_ids": "rules-builder/symbol-ids",
  "grammar_parser/build_rule_stack": "grammar-parser/build-rule-stack",
  "grammar_graph/colorize": "grammar-graph/colorize",
  "grammar_graph/get_input_as_code_points": "grammar-graph/get-input-as-code-points",
  "grammar_graph/get_parent_stack_id": "grammar-graph/get-parent-stack-id",
  "grammar_graph/get_serialized_rule_key": "grammar-graph/get-serialized-rule-key",
  "grammar_graph/grammar_graph_types": "grammar-graph/grammar-graph-types",
  "grammar_graph/graph": "grammar-graph/graph",
  "grammar_graph/graph_node": "grammar-graph/graph-node",
  "grammar_graph/graph_pointer": "grammar-graph/graph-pointer",
  "grammar_graph/parse_state": "grammar-graph/parse-state",
  "grammar_graph/pointers": "grammar-graph/pointers",
  "grammar_graph/print": "grammar-graph/print",
  "grammar_graph/rule_ref": "grammar-graph/rule-ref",
  "grammar_graph/type_guards": "grammar-graph/type-guards",
};

/** modules that also need a default export forwarded */
const WITH_DEFAULT = new Set(["__init__", "GBNF"]);

const HEADER =
  "// Generated by scripts/build-python-layout.mjs - re-exports the TypeScript port under\n" +
  "// the reference implementation's Python module path. Do not edit.\n";

for (const [pythonPath, tsPath] of Object.entries(MODULES)) {
  const outDir = path.join(ROOT, "gbnf", path.dirname(pythonPath));
  await mkdir(outDir, { recursive: true });

  const depth = pythonPath.split("/").length;
  const prefix = `${"../".repeat(depth)}src/${tsPath}`;
  const withDefault = WITH_DEFAULT.has(pythonPath);

  for (const ext of ["ts", "js"]) {
    const target = `${prefix}.${ext}`;
    const lines = [
      HEADER,
      `export * from "${target}";`,
      // the snake_case aliases, so the Python function names resolve here too
      `export * from "${"../".repeat(depth)}src/compat.${ext}";`,
    ];
    if (withDefault) {
      lines.push(`export { default } from "${target}";`);
    }
    await writeFile(
      path.join(ROOT, "gbnf", `${pythonPath}.${ext}`),
      `${lines.join("\n")}\n`,
    );
  }
}

// `gbnf/index.*` as well as `gbnf/__init__.*`, since ESM has no directory resolution.
for (const ext of ["ts", "js"]) {
  await writeFile(
    path.join(ROOT, "gbnf", `index.${ext}`),
    `${HEADER}export * from "./__init__.${ext}";\nexport { default } from "./__init__.${ext}";\n`,
  );
}

console.log(`wrote ${Object.keys(MODULES).length + 1} python-layout modules`);
