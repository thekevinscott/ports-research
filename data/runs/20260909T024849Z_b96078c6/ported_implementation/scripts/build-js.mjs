/**
 * Two build outputs, both generated from the `.ts` sources (the source of truth):
 *
 * 1. `src/**\/*.js` — one-line re-exports of the sibling `.ts` module. These exist so that
 *    `.js` import specifiers resolve; because they forward to the same module, a consumer
 *    mixing `.js` and `.ts` specifiers still gets one set of classes (`instanceof` works).
 * 2. `dist/**` — a self-contained, type-free copy for toolchains that cannot load
 *    TypeScript at all.
 *
 * Run `node scripts/build-js.mjs` after changing anything under `src/`.
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");

const walk = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".d.ts")) {
      files.push(full);
    }
  }
  return files;
};

const hasDefaultExport = (source) =>
  /^export\s+default\s/m.test(source) || /^export\s*\{[^}]*\bdefault\b/m.test(source);

const files = await walk(SRC);
await rm(DIST, { recursive: true, force: true });

for (const file of files) {
  const source = await readFile(file, "utf8");
  const name = path.basename(file);

  // 1. the forwarding shim next to the source
  const shim = [
    "// Generated by scripts/build-js.mjs - forwards to the TypeScript source so that",
    "// `.js` and `.ts` specifiers resolve to the same module. Do not edit.",
    `export * from "./${name}";`,
    ...(hasDefaultExport(source) ? [`export { default } from "./${name}";`] : []),
    "",
  ].join("\n");
  await writeFile(`${file.slice(0, -3)}.js`, shim);

  // 2. the self-contained, type-free copy under dist/
  const relative = path.relative(SRC, file);
  const out = path.join(DIST, `${relative.slice(0, -3)}.js`);
  await mkdir(path.dirname(out), { recursive: true });
  const stripped = stripTypeScriptTypes(source, { mode: "strip" }).replace(
    /(from\s*["'])(\.\.?\/[^"']+)\.ts(["'])/g,
    "$1$2.js$3",
  );
  await writeFile(out, stripped);
}

// type declarations for the dist build point back at the sources
await writeFile(
  path.join(DIST, "index.d.ts"),
  'export * from "../src/index.ts";\nexport { default } from "../src/gbnf.ts";\n',
);

console.log(`wrote ${files.length} shims under src/ and ${files.length} modules under dist/`);
